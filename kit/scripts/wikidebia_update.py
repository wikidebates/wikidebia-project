def _canonical_top_level_parameters(text: str, language: str, page_type: str) -> tuple[str, list[str], dict[str, str]]:
    model, positional, params = top_level_parameter_map(text, language, page_type)
    canonical: dict[str, str] = {}
    for raw_name, value in params.items():
        name = _canonical_parameter_name(language, page_type, raw_name)
        canonical[name] = value
    return model, positional, canonical


def changed_top_level_parameters(old_text: str, new_text: str, language: str, page_type: str) -> list[str]:
    """Return canonical top-level parameters whose presence or value changed.

    The list is deterministic and intentionally ignores parameter spelling aliases:
    a historical ``nom=`` read as ``nom-consacré`` does not by itself fabricate a
    semantic change. Structural changes outside named parameters are represented by
    the synthetic ``__structure__`` marker.
    """
    old_model, old_positional, old_params = _canonical_top_level_parameters(old_text, language, page_type)
    new_model, new_positional, new_params = _canonical_top_level_parameters(new_text, language, page_type)
    changed = sorted(
        name for name in (set(old_params) | set(new_params))
        if old_params.get(name) != new_params.get(name)
    )
    if normalize_key(old_model) != normalize_key(new_model) or old_positional != new_positional:
        changed.append("__structure__")
    return changed


def remote_diff_is_only_preservable_metadata(
    prior_text: str,
    remote_text: str,
    language: str,
    page_type: str,
) -> tuple[bool, list[str]]:
    """Prove that remote drift is confined to metadata preserved on update.

    Top-level protected parameters are compared semantically, including their
    historical aliases. Text outside the main template must remain equivalent;
    this prevents metadata-only adoption from hiding categories, interwiki
    links, or any other out-of-template human change.
    """
    changed = changed_top_level_parameters(prior_text, remote_text, language, page_type)
    preservable = set(PROTECTED_LIFECYCLE_PARAMETERS[(language, page_type)])
    preservable.update(CONCURRENTLY_PRESERVABLE_METADATA[(language, page_type)])
    if not set(changed).issubset(preservable):
        return False, changed

    expected = {
        ("fr", "debate"): "debat", ("en", "debate"): "debate",
        ("fr", "argument"): "argument", ("en", "argument"): "argument",
    }[(language, page_type)]

    def outside_main_template(text: str) -> str:
        calls = [call for call in iter_templates(text or "") if normalize_key(call.name) == expected]
        if not calls:
            raise UpdateError(f"Modèle principal introuvable ({language}/{page_type})")
        call = max(calls, key=lambda item: len(item.raw))
        return normalize_wikicode(text.replace(call.raw, "{{WIKIDEBIA_MAIN_TEMPLATE}}", 1))

    return outside_main_template(prior_text) == outside_main_template(remote_text), changed


def preserve_remote_top_level_parameters(
    remote_text: str,
    proposed_text: str,
    language: str,
    page_type: str,
    names: Iterable[str],
) -> tuple[str, dict[str, Any]]:
    """Overlay an explicit, narrowly scoped set of remote template parameters."""
    wanted = tuple(dict.fromkeys(str(name) for name in names))
    if not wanted:
        return proposed_text, {}
    _, _, remote_params = _canonical_top_level_parameters(remote_text, language, page_type)
    expected = {
        ("fr", "debate"): "debat", ("en", "debate"): "debate",
        ("fr", "argument"): "argument", ("en", "argument"): "argument",
    }[(language, page_type)]
    calls = [call for call in iter_templates(proposed_text or "") if normalize_key(call.name) == expected]
    if not calls:
        raise UpdateError(f"Modèle principal introuvable ({language}/{page_type})")
    call = max(calls, key=lambda item: len(item.raw))
    parsed = parse_template(call.raw)
    if parsed is None:
        raise UpdateError(f"Modèle principal illisible ({language}/{page_type})")

    normalized_wanted = {normalize_key(name): name for name in wanted}
    rows = [f"{{{{{parsed.name}"]
    rows.extend(f"|{value}" for value in parsed.positional)
    seen: set[str] = set()
    for raw_name, value in parsed.params.items():
        canonical = _canonical_parameter_name(language, page_type, raw_name)
        selected = normalized_wanted.get(normalize_key(canonical))
        if selected is None:
            rows.append(f"|{raw_name}={value}")
            continue
        seen.add(selected)
        if selected in remote_params:
            rows.append(f"|{selected}={remote_params[selected]}")
    for name in wanted:
        if name not in seen and name in remote_params:
            rows.append(f"|{name}={remote_params[name]}")
    rows.append("}}")
    effective = proposed_text.replace(call.raw, "\n".join(rows), 1)
    _, _, effective_params = _canonical_top_level_parameters(effective, language, page_type)
    audit = {
        name: {
            "remote": remote_params.get(name),
            "effective": effective_params.get(name),
            "present": name in remote_params,
        }
        for name in wanted
    }
    if any(
        (name in effective_params) != (name in remote_params)
        or effective_params.get(name) != remote_params.get(name)
        for name in wanted
    ):
        raise UpdateError(f"Échec de préservation des métadonnées distantes ({language}/{page_type})")
    return effective, audit


def _join_summary_items(items: list[str], language: str) -> str:
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    conjunction = " et " if language == "fr" else " and "
    if len(items) == 2:
        return conjunction.join(items)
    return ", ".join(items[:-1]) + conjunction + items[-1]


def _summary_groups(language: str, page_type: str, changed: Iterable[str]) -> list[str]:
    names = set(changed)
    groups: list[str] = []

    if language == "fr" and page_type == "debate":
        rules = [
            ({"sujet", "sujet-développé"}, "du cadrage du débat"),
            ({"introduction"}, "de l'introduction"),
            ({"arguments-pour", "arguments-contre"}, "du plan argumentatif"),
            ({"articles-Wikipédia"}, "des articles Wikipédia"),
            ({
                "bibliographie-pour", "bibliographie-contre", "bibliographie-ni-pour-ni-contre",
                "sitographie-pour", "sitographie-contre", "sitographie-ni-pour-ni-contre",
                "vidéographie-pour", "vidéographie-contre", "vidéographie-ni-pour-ni-contre",
            }, "des références"),
            ({"rubriques"}, "des rubriques"),
            ({"mots-clés"}, "des mots-clés"),
            ({"interlangue"}, "du lien interlangue"),
        ]
        metadata_label = "des métadonnées"
        fallback = "du contenu de la page"
    elif language == "fr":
        rules = [
            ({"nom-consacré"}, "du nom consacré"),
            ({"résumé"}, "du résumé"),
            ({"citations"}, "des citations"),
            ({"références-bibliographiques", "références-sitographiques", "références-vidéographiques"}, "des références"),
            ({"justifications"}, "des justifications"),
            ({"objections"}, "des objections"),
            ({"débat-dédié"}, "du débat dédié"),
            ({"rubriques"}, "des rubriques"),
            ({"mots-clés"}, "des mots-clés"),
            ({"interlangue"}, "du lien interlangue"),
        ]
        metadata_label = "des métadonnées"
        fallback = "du contenu de la page"
    elif language == "en" and page_type == "debate":
        rules = [
            ({"topic", "expanded-topic"}, "the debate framing"),
            ({"introduction"}, "the introduction"),
            ({"pro-arguments", "con-arguments"}, "the argument map"),
            ({"wikipedia-articles"}, "the Wikipedia articles"),
            ({
                "pro-bibliography", "con-bibliography", "bibliography",
                "pro-webliography", "con-webliography", "webliography",
                "pro-videography", "con-videography", "videography",
            }, "the references"),
            ({"sections"}, "the sections"),
            ({"keywords"}, "the keywords"),
        ]
        metadata_label = "the metadata"
        fallback = "the page content"
    else:
        rules = [
            ({"established-name"}, "the established name"),
            ({"summary"}, "the summary"),
            ({"quotes"}, "the quotes"),
            ({"bibliography", "webliography", "videography"}, "the references"),
            ({"justifications"}, "the justifications"),
            ({"objections"}, "the objections"),
            ({"dedicated-debate"}, "the dedicated debate"),
            ({"sections"}, "the sections"),
            ({"keywords"}, "the keywords"),
        ]
        metadata_label = "the metadata"
        fallback = "the page content"

    consumed: set[str] = set()
    for parameter_names, label in rules:
        if names & parameter_names:
            groups.append(label)
            consumed |= parameter_names

    lifecycle_prefixes = (
        "avancement", "avertissements-", "date-création",
        "progress", "title-warnings", "debate-warnings", "argument-warnings",
        "summary-warnings", "reference-warnings", "justification-warnings",
        "objection-warnings", "creation-date", "initialisation", "initialization",
    )
    unconsumed = {
        name for name in names
        if name not in consumed
        and name != "__structure__"
    }
    if any(name.startswith(lifecycle_prefixes) for name in unconsumed):
        groups.append(metadata_label)
        unconsumed = {name for name in unconsumed if not name.startswith(lifecycle_prefixes)}

    if "__structure__" in names or unconsumed:
        groups.append(fallback)

    # Ordered de-duplication in case multiple low-level parameters collapse to one label.
    return list(dict.fromkeys(groups))


def content_diff_edit_summary(old_text: str, new_text: str, language: str, page_type: str) -> str:
    changed = changed_top_level_parameters(old_text, new_text, language, page_type)
    groups = _summary_groups(language, page_type, changed)
    if language == "fr":
        return "Mise à jour " + _join_summary_items(groups or ["du contenu de la page"], language)
    return "Update to " + _join_summary_items(groups or ["the page content"], language)


def assert_summary_change_authorized(
    old_text: str, new_text: str, language: str, page_type: str,
    authorization: dict[str, Any] | None = None,
) -> None:
    """An existing argument's summary is outside a generic correction scope.

    Creation is handled separately. Updates, including filling an empty field,
    removal and renames, need a page-specific, quoted user instruction. A broad
    publication/adoption authorization does not grant this editorial permission.
    """
    if page_type != "argument":
        return
    key = normalize_key("résumé" if language == "fr" else "summary")
    def summary(text: str) -> dict[str, str]:
        _, _, params = top_level_parameter_map(text, language, page_type)
        return {normalize_key(name): value for name, value in params.items()
                if normalize_key(name) == key}
    if summary(old_text) == summary(new_text):
        return
    if not (
        isinstance(authorization, dict)
        and authorization.get("decision") == "explicit_user_request"
        and authorization.get("action") in {"edit", "restore"}
        and isinstance(authorization.get("instruction"), str)
        and authorization["instruction"].strip()
    ):
        raise UpdateError("Modification du résumé d’argument sans demande utilisateur explicite et spécifique")


def assert_citation_change_authorized(
    old_text: str, new_text: str, authorization: dict[str, Any] | None = None,
) -> None:
    """Keep every existing quote, including its attribution and source.

    A missing/unverified source is not permission to delete a quotation. Generic
    correction, deduplication and publication authorizations do not grant it.
    Count occurrences so removing a duplicate is also an editorial deletion.
    Inspect the whole page, including quotes outside the usual citation field.
    """
    def citations(text: str) -> Counter:
        return Counter(call.raw for call in iter_templates(text)
                       if normalize_key(call.name) in {"citation", "quote"})
    if not citations(old_text) - citations(new_text):
        return
    if not (
        isinstance(authorization, dict)
        and authorization.get("decision") == "explicit_user_request"
        and authorization.get("action") in ("edit", "restore")
        and isinstance(authorization.get("instruction"), str)
        and authorization["instruction"].strip()
    ):
        raise UpdateError("Suppression ou réécriture d’une citation existante sans demande utilisateur explicite et spécifique")


